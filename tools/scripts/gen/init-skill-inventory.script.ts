#!/usr/bin/env bun
/**
 * init-skill-inventory.script.ts — the adoption plan's skill table,
 * generated from the one place skills declare themselves.
 *
 * ## Why it is generated rather than written
 *
 * The table has to be a static embedded constant: the plan is built with
 * a reader bounded to the TARGET workspace, so our own skill set cannot
 * be read from disk there, and the manifest carries a timestamp that
 * would make the rendered plan non-deterministic. That reasoning is
 * sound, and it is why the table was hand-written with a comment asking
 * the next person to keep it in step with `packages/core/skills/manifest.json`.
 *
 * It did not stay in step. Measured before this generator existed: the
 * plan listed 18 of 27 skills, disagreed with the manifest about who
 * FIVE of them apply to, and omitted two skills that `init` installs —
 * so what an adopter was promised and what they received were two
 * different lists.
 *
 * Generating it keeps every property the hand-written table had (static,
 * embedded, id-sorted, no timestamp) and removes the only one nobody
 * wanted: the ability to disagree.
 *
 * Exit codes: 0 — written, or `--check` and already current. 1 —
 * `--check` and stale.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { repoRoot } from '../lib/repo-root';

const MANIFEST = 'packages/core/skills/manifest.json';
const TARGET = 'packages/cli/src/lib/init/init-skill-inventory.generated.ts';

interface IManifestSkill {
	readonly id: string;
	readonly appliesTo?: readonly string[];
}

const render = (skills: readonly IManifestSkill[]): string => {
	const rows = [...skills]
		.sort((left, right) => left.id.localeCompare(right.id))
		.map((skill) => {
			const applies = (skill.appliesTo ?? ['@delendai/*']).join(', ');
			// One property per line, and the value moved to its own line
			// once the property would pass the formatter's 80-column
			// width — which is exactly what the formatter does. A
			// generated file the formatter would rewrite drifts against
			// `format:all:check` for ever after.
			const inline = `\t\tappliesTo: '${applies}',`;
			const appliesLines =
				inline.replaceAll('\t', '    ').length > 80
					? [`\t\tappliesTo:`, `\t\t\t'${applies}',`]
					: [inline];
			return [
				'\t{',
				`\t\tid: '${skill.id}',`,
				...appliesLines,
				'\t},',
			].join('\n');
		});
	return [
		'// GENERATED by tools/scripts/gen/init-skill-inventory.script.ts.',
		'// Edit packages/core/skills/manifest.json instead: a skill declares',
		'// who it is for in exactly one place.',
		'',
		"import type { ICanonicalSkill } from '../../contracts/interfaces/init.interface';",
		'',
		'/** OUR canonical skills, as the core skill manifest declares them. */',
		'export const CANONICAL_SKILLS: readonly ICanonicalSkill[] = [',
		...rows,
		'];',
		'',
	].join('\n');
};

const main = async (): Promise<number> => {
	const root = repoRoot();
	const manifest = JSON.parse(
		await readFile(join(root, MANIFEST), 'utf8'),
	) as { readonly skills?: readonly IManifestSkill[] };
	const wanted = render(manifest.skills ?? []);
	const targetPath = join(root, TARGET);
	const current = await readFile(targetPath, 'utf8').catch(() => undefined);
	if (current === wanted) {
		process.stdout.write(`init-skill-inventory: up to date (${TARGET})\n`);
		return 0;
	}
	if (process.argv.includes('--check')) {
		process.stderr.write(
			`✖ init-skill-inventory: ${TARGET} is stale — run \`bun tools/scripts/gen/init-skill-inventory.script.ts\`.\n`,
		);
		return 1;
	}
	await writeFile(targetPath, wanted, 'utf8');
	process.stdout.write(`init-skill-inventory: wrote ${TARGET}\n`);
	return 0;
};

process.exitCode = await main();
