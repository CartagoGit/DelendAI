#!/usr/bin/env bun
import { readdirSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, relative, resolve } from 'node:path';

import observabilityManifest from '../../../plugins/observability/plugin.manifest';
import {
	buildObservabilityToolSourcePathMap,
	listObservabilityToolIds,
} from '../../../plugins/observability/src/lib/tools/registry';
import {
	buildProvenanceGraph,
	PROVENANCE_NODE_KINDS,
	PROVENANCE_RELATION_DEFINITIONS,
	type IProvenanceEventInput,
	type IProvenanceGraph,
} from '../../../plugins/observability/src/public';
import { REPOSITORY_URL } from '@delendai/core/public';

const OUTPUT_REL =
	'docs/delendai/generated/observability-provenance.generated.md';
const OUTPUT_DIR_REL = 'docs/delendai/generated';
const REPO_URL = REPOSITORY_URL;
const PROPOSAL_PATH =
	'docs/delendai/proposals/ready/feats/f00392-adaptive-preferred-path-proposals-facade-provenance-generated-truth-and-vs-code-benchmark.md';

const REPO_ROOT_ABS = resolve(
	dirname(fileURLToPath(import.meta.url)),
	'../../..',
);
const OBSERVABILITY_ROOT_REL = 'plugins/observability';
const OBSERVABILITY_ROOT_ABS = resolve(REPO_ROOT_ABS, OBSERVABILITY_ROOT_REL);

const normalizeRelativePath = (path: string): string =>
	path.replace(/\\/g, '/');

const listSpecPathsRecursive = (dirAbs: string): string[] => {
	const paths: string[] = [];
	for (const entry of readdirSync(dirAbs, { withFileTypes: true })) {
		const entryAbs = resolve(dirAbs, entry.name);
		if (entry.isDirectory()) {
			paths.push(...listSpecPathsRecursive(entryAbs));
			continue;
		}
		if (!entry.isFile() || !entry.name.endsWith('.spec.ts')) continue;
		paths.push(normalizeRelativePath(relative(REPO_ROOT_ABS, entryAbs)));
	}
	return paths;
};

export const listObservabilityValidationTestPaths = (): readonly string[] =>
	listSpecPathsRecursive(OBSERVABILITY_ROOT_ABS).sort((left, right) =>
		left.localeCompare(right),
	);

const buildExampleGraphInput = (): IProvenanceEventInput => ({
	agent: 'finch',
	proposalId: 'f00392',
	sliceId: 'S2',
	toolIds: [...listObservabilityToolIds()],
	testPaths: [...listObservabilityValidationTestPaths()],
	commitShas: ['8514f99'],
	releaseTags: ['v0.1.1'],
	pullRequests: ['52'],
	userData: ['finch@example.com', 'secret-token'],
});

export interface IProvenanceTruthSnapshot {
	readonly manifest: {
		readonly id: string;
		readonly package: string;
		readonly summary: string;
		readonly capabilities: readonly string[];
	};
	readonly topology: {
		readonly nodeKinds: readonly string[];
		readonly relations: readonly {
			readonly from: string;
			readonly relation: string;
			readonly to: string;
		}[];
	};
	readonly registrations: {
		readonly toolIds: readonly string[];
		readonly toolPaths: Readonly<Record<string, string>>;
		readonly testPaths: readonly string[];
	};
	readonly exampleGraph: IProvenanceGraph;
}

const toDocRelativeHref = (href: string): string => {
	if (/^https?:\/\//u.test(href)) return href;
	return relative(OUTPUT_DIR_REL, href).replace(/\\/g, '/');
};

export const buildProvenanceTruthSnapshot = (): IProvenanceTruthSnapshot => {
	const toolIds = [...listObservabilityToolIds()];
	const toolPaths = buildObservabilityToolSourcePathMap();
	const testPaths = [...listObservabilityValidationTestPaths()];
	const exampleGraph = buildExampleGraphInput();
	const testPathMap = Object.fromEntries(
		testPaths.map((path) => [path, path]),
	);
	return {
		manifest: {
			id: observabilityManifest.id,
			package: observabilityManifest.package,
			summary: observabilityManifest.summary,
			capabilities: observabilityManifest.capabilities ?? [],
		},
		topology: {
			nodeKinds: [...PROVENANCE_NODE_KINDS],
			relations: PROVENANCE_RELATION_DEFINITIONS.map((entry) => ({
				...entry,
			})),
		},
		registrations: {
			toolIds,
			toolPaths,
			testPaths,
		},
		exampleGraph: buildProvenanceGraph(exampleGraph, {
			repoUrl: REPO_URL,
			proposalPaths: {
				f00392: PROPOSAL_PATH,
			},
			toolPaths,
			testPaths: testPathMap,
		}),
	};
};

const renderLink = (label: string, href: string | null): string =>
	href === null ? label : `[${label}](${toDocRelativeHref(href)})`;

export const renderProvenanceTruthMarkdown = (
	snapshot: IProvenanceTruthSnapshot,
): string => {
	const lines: string[] = [];
	lines.push(
		'<!-- Auto-generated by bun tools/scripts/gen/provenance-truth.script.ts -->',
	);
	lines.push('');
	lines.push('# Observability provenance truth');
	lines.push('');
	lines.push(
		'Generated from the observability manifest and the provenance graph contract exported by the plugin public surface.',
	);
	lines.push('');
	lines.push('## Plugin contract');
	lines.push('');
	lines.push(
		`- Manifest: [plugins/observability/plugin.manifest.ts](${toDocRelativeHref('plugins/observability/plugin.manifest.ts')})`,
	);
	lines.push(`- Plugin id: ${snapshot.manifest.id}`);
	lines.push(`- Package: ${snapshot.manifest.package}`);
	lines.push(`- Summary: ${snapshot.manifest.summary}`);
	lines.push(
		`- Declared capabilities: ${snapshot.manifest.capabilities.join(', ') || 'none'}`,
	);
	lines.push('');
	lines.push('## Registered tools');
	lines.push('');
	lines.push(`- Registered tools: ${snapshot.registrations.toolIds.length}`);
	lines.push('| tool id | source |');
	lines.push('| --- | --- |');
	for (const toolId of snapshot.registrations.toolIds) {
		const sourcePath = snapshot.registrations.toolPaths[toolId] ?? null;
		lines.push(
			`| ${toolId} | ${renderLink(sourcePath ?? 'none', sourcePath)} |`,
		);
	}
	lines.push('');
	lines.push('## Validation coverage');
	lines.push('');
	lines.push(
		`- Validation tests: ${snapshot.registrations.testPaths.length}`,
	);
	lines.push('| test | link |');
	lines.push('| --- | --- |');
	for (const testPath of snapshot.registrations.testPaths) {
		lines.push(`| ${testPath} | ${renderLink(testPath, testPath)} |`);
	}
	lines.push('');
	lines.push('## Topology');
	lines.push('');
	lines.push(`- Node kinds: ${snapshot.topology.nodeKinds.length}`);
	lines.push(`- Relations: ${snapshot.topology.relations.length}`);
	lines.push(`- Example graph nodes: ${snapshot.exampleGraph.nodes.length}`);
	lines.push(`- Example graph edges: ${snapshot.exampleGraph.edges.length}`);
	lines.push(
		`- Example graph redactions: ${snapshot.exampleGraph.redactions}`,
	);
	lines.push('');
	lines.push('| kind | source of truth |');
	lines.push('| --- | --- |');
	for (const kind of snapshot.topology.nodeKinds) {
		lines.push(`| ${kind} | public provenance contract |`);
	}
	lines.push('');
	lines.push('| from | relation | to |');
	lines.push('| --- | --- | --- |');
	for (const relation of snapshot.topology.relations) {
		lines.push(
			`| ${relation.from} | ${relation.relation} | ${relation.to} |`,
		);
	}
	lines.push('');
	lines.push('## Example graph');
	lines.push('');
	lines.push(
		`Reference slice: [f00392 / S2](${toDocRelativeHref(PROPOSAL_PATH)}#slices)`,
	);
	lines.push('');
	lines.push('| node | label | link |');
	lines.push('| --- | --- | --- |');
	for (const node of snapshot.exampleGraph.nodes) {
		lines.push(
			`| ${node.id} | ${node.label} | ${renderLink(node.href ?? 'none', node.href)} |`,
		);
	}
	lines.push('');
	lines.push('| from | relation | to |');
	lines.push('| --- | --- | --- |');
	for (const edge of snapshot.exampleGraph.edges) {
		lines.push(`| ${edge.from} | ${edge.relation} | ${edge.to} |`);
	}
	lines.push('');
	lines.push('## Drift');
	lines.push('');
	lines.push(
		'- Regenerate with `bun tools/scripts/gen/provenance-truth.script.ts`.',
	);
	lines.push(
		'- Check drift with `bun tools/scripts/gen/provenance-truth.script.ts --check` or `bun run gen:web-pages:check`.',
	);
	return `${lines.join('\n')}\n`;
};

export const generateProvenanceTruth = async (): Promise<string> => {
	const snapshot = buildProvenanceTruthSnapshot();
	return renderProvenanceTruthMarkdown(snapshot);
};

export interface IRunOptions {
	readonly argv: readonly string[];
	readonly outputPath?: string;
	readonly readText?: (path: string) => Promise<string | null>;
	readonly writeText?: (path: string, text: string) => Promise<void>;
}

export const run = async (options: IRunOptions): Promise<number> => {
	const outputPath = options.outputPath ?? OUTPUT_REL;
	const markdown = await generateProvenanceTruth();
	const check = options.argv.includes('--check');
	const readText =
		options.readText ??
		(async (path: string) => readFile(path, 'utf8').catch(() => null));
	const writeText =
		options.writeText ??
		(async (path: string, text: string) => {
			await mkdir(dirname(path), { recursive: true });
			await writeFile(path, text, 'utf8');
		});
	const current = await readText(outputPath);
	if (check) {
		if (current === markdown) {
			console.log(`provenance-truth: no drift in ${outputPath}`);
			return 0;
		}
		console.error(`provenance-truth: drift detected in ${outputPath}`);
		console.error(
			'  fix: bun tools/scripts/gen/provenance-truth.script.ts',
		);
		return 1;
	}
	if (current !== markdown) {
		await writeText(outputPath, markdown);
		console.log(`provenance-truth: wrote ${outputPath}`);
		return 0;
	}
	console.log(`provenance-truth: unchanged ${outputPath}`);
	return 0;
};

if (import.meta.main) {
	process.exit(await run({ argv: process.argv.slice(2) }));
}
