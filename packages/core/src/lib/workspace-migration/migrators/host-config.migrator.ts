/**
 * host-config.migrator.ts — b00239 S4.
 *
 * Rewrites host-side MCP configuration files in place.
 *
 * ## Scope, narrow on purpose
 *
 * Owns every project-level MCP config a host reads from the workspace:
 * `.vscode/mcp.json`, the root `.mcp.json`, `.cursor/mcp.json`,
 * `.continue/config.json` and `.codex/config.toml`. A rename that left
 * one of them naming the old server left that host starting a server
 * that no longer exists. The user-level configs in the home directory
 * are the host-scope migration's.
 *
 * ## Why the editor's config is read as JSONC
 *
 * `.vscode/mcp.json` is the VS Code spec, and VS Code parses it as
 * JSONC: a line comment above the object is legal there, and the
 * scripts that generate the file routinely write one ("generated by
 * <script> — do not edit by hand"). Reading it with `JSON.parse` made
 * every such file unreadable, and an unreadable file raised an error
 * that reached the boot of every project that has one.
 *
 * Two rules keep the leniency from becoming sloppiness:
 *
 *  - a file plain JSON can parse is still rewritten exactly as it
 *    always was — same rules, same bytes, same indentation. Only a file
 *    that NEEDS the lenient reader is treated as a JSONC document;
 *  - a JSONC document is edited IN PLACE, through the JSONC edit
 *    applicator, so the comments, the key order and the formatting the
 *    owner wrote survive the rewrite. A document that is neither plain
 *    JSON nor valid JSONC is refused with the same error as before: a
 *    file that is genuinely broken is still reported, never
 *    half-understood.
 *
 * ## What gets rewritten
 *
 * The `servers` map (or `mcpServers`, the Cursor / Claude spelling)
 * is walked; every string field of a server entry is rewritten, and so
 * is every string in its `args` and `env` arrays. The name of the
 * server itself is rewritten with them.
 */
import { access, readFile } from 'node:fs/promises';
import { join } from 'node:path';

import type {
	IMigration,
	IMigrationContext,
	IMigrationPlanStep,
} from '../../contracts/interfaces/workspace-migration.interface';

import {
	applyJsoncEdits,
	parseJsonc,
	type IJsoncEdit,
} from '../../config/jsonc-document';
import { writeFileAtomic } from '../../shared/atomic-write';
import {
	rewriteCodexConfig,
	rewriteServerArrays,
} from './host-config-rewrites';
import {
	rewriteIdentityInString,
	stringHasLegacyIdentity,
} from './identity-renames';

/** The editor's project MCP config. Stable for the lifetime of v1. */
export const HOST_CONFIG_NAME = '.vscode/mcp.json';

/**
 * Every project MCP config a host reads: the editor's, and the root
 * `.mcp.json` other hosts read. The root one kept running the old CLI
 * after a migration that rewrote only the editor's.
 */
const HOST_CONFIG_NAMES = [
	HOST_CONFIG_NAME,
	'.mcp.json',
	'.cursor/mcp.json',
	'.continue/config.json',
] as const;

/**
 * Configs other hosts own and write as JSONC — Continue's carries
 * comments. Read tolerantly: one that cannot be read is not ours to
 * judge and is left alone, never a start-up failure; one that names the
 * old server is rewritten in its text, so its comments survive.
 */
const TOLERANT_HOST_CONFIG_NAMES: ReadonlySet<string> = new Set([
	'.cursor/mcp.json',
	'.continue/config.json',
]);

/**
 * Codex's project config, TOML. Its `[mcp_servers.<name>]` tables are
 * rewritten line by line, and nothing outside them is read.
 */
const CODEX_CONFIG_NAME = '.codex/config.toml';

/** Stable id recorded in the journal. NOT a number, by design. */
export const HOST_CONFIG_MIGRATOR_ID = 'hostConfigMigrator:v1';

/** Maps that hold server entries under either of the two spellings. */
const SERVER_MAPS = ['servers', 'mcpServers'] as const;

/** Within one server entry, these are the string-typed fields. */
const SERVER_STRING_FIELDS = ['command', 'cwd', 'type', 'description'] as const;

export class HostConfigParseError extends Error {
	readonly file: string;
	constructor(file: string, reason: string) {
		super(`host config ${file} is not valid JSON: ${reason}`);
		this.name = 'HostConfigParseError';
		this.file = file;
	}
}

const pathExists = async (absolutePath: string): Promise<boolean> =>
	access(absolutePath).then(
		() => true,
		() => false,
	);

/**
 * A host config, and the text it was read from.
 *
 * The text is kept because a JSONC document is edited in place: the
 * rewritten value is not what the file becomes — the file becomes the
 * original with the rewritten members applied to it.
 */
interface IHostConfigDocument {
	readonly text: string;
	readonly value: Record<string, unknown>;
	/**
	 * Whether plain JSON could parse it. A plain JSON file is rewritten
	 * exactly as it always was; only a file that needs the lenient reader
	 * is edited in place.
	 */
	readonly plain: boolean;
}

/**
 * Read a host config the editor reads.
 *
 * A file plain JSON can parse is a plain JSON file. A file plain JSON
 * cannot parse is a JSONC document — a comment, a trailing comma — and
 * it is read leniently. A document that is neither is refused with the
 * same error as before, so a file that is genuinely broken is reported
 * instead of half-understood.
 */
const readHostConfig = async (
	absolutePath: string,
): Promise<IHostConfigDocument> => {
	const text = await readFile(absolutePath, 'utf8');
	let strict: unknown;
	try {
		strict = JSON.parse(text);
	} catch {
		strict = undefined;
	}
	if (strict !== undefined) {
		if (
			strict === null ||
			typeof strict !== 'object' ||
			Array.isArray(strict)
		) {
			throw new HostConfigParseError(
				absolutePath,
				'top-level value is not an object',
			);
		}
		return {
			text,
			value: strict as Record<string, unknown>,
			plain: true,
		};
	}
	const parsed = parseJsonc(text);
	const first = parsed.errors[0];
	if (first !== undefined)
		throw new HostConfigParseError(absolutePath, first.message);
	if (
		parsed.value === null ||
		typeof parsed.value !== 'object' ||
		Array.isArray(parsed.value)
	) {
		throw new HostConfigParseError(
			absolutePath,
			'top-level value is not an object',
		);
	}
	return {
		text,
		value: parsed.value as Record<string, unknown>,
		plain: false,
	};
};

/**
 * Rewrite one server entry's string-typed fields and any string in
 * its `args` / `env` arrays. The map key (the server name itself) is
 * also rewritten — the legacy server id → new server id is the
 * canonical rename of the project's MCP server.
 */
/**
 * Rewrite a nested record (e.g. the `env` object inside a server
 * entry) the same way the top-level `servers` map is rewritten:
 * keys and string values both walk `rewriteIdentityInString`. The
 * rebrand routinely produces env keys like `MCP_VERTEX_HOME` →
 * `DELENDAI_HOME`; a migrator that only touched values would leave
 * the keys half-converted, which is the failure the engine's
 * residual scanner (S8) is meant to catch.
 */
const rewriteNestedRecord = (
	record: Record<string, unknown>,
): { readonly changed: boolean; readonly next: Record<string, unknown> } => {
	let changed = false;
	const next: Record<string, unknown> = {};
	for (const [key, child] of Object.entries(record)) {
		const rewrittenKey = rewriteIdentityInString(key);
		if (rewrittenKey !== key) changed = true;
		if (typeof child === 'string') {
			const rewrittenValue = rewriteIdentityInString(child);
			if (rewrittenValue !== child) changed = true;
			next[rewrittenKey] = rewrittenValue;
			continue;
		}
		next[rewrittenKey] = child;
	}
	return { changed, next };
};

const rewriteServerEntry = (
	key: string,
	value: unknown,
): { changed: boolean; nextKey: string; nextValue: unknown } => {
	let changed = false;
	const nextKey = rewriteIdentityInString(key);
	if (nextKey !== key) changed = true;

	if (value === null || typeof value !== 'object' || Array.isArray(value)) {
		if (typeof value === 'string') {
			const rewritten = rewriteIdentityInString(value);
			if (rewritten !== value) changed = true;
			return { changed, nextKey, nextValue: rewritten };
		}
		return { changed, nextKey, nextValue: value };
	}

	const entry = value as Record<string, unknown>;
	const next: Record<string, unknown> = {};
	for (const [field, child] of Object.entries(entry)) {
		if (typeof child === 'string') {
			const rewrittenField = rewriteIdentityInString(field);
			const rewrittenChild = rewriteIdentityInString(child);
			if (rewrittenField !== field) changed = true;
			if (rewrittenChild !== child) changed = true;
			next[rewrittenField] = rewrittenChild;
			continue;
		}
		if (Array.isArray(child) && (field === 'args' || field === 'env')) {
			let childChanged = false;
			const nextArray = child.map((element) => {
				if (typeof element !== 'string') return element;
				const rewritten = rewriteIdentityInString(element);
				if (rewritten !== element) childChanged = true;
				return rewritten;
			});
			if (childChanged) changed = true;
			next[field] = nextArray;
			continue;
		}
		// Nested object fields (`env`, `metadata`, future
		// additions) get the same key-rewriting walk as the top-level
		// `servers` map: every key carries the identity through
		// `MCP_VERTEX_HOME` → `DELENDAI_HOME` style rewrites, every
		// string value walks `rewriteIdentityInString`. The engine
		// stays narrow because only env-style records appear in the
		// MCP config we own; a non-record value here is left alone.
		if (
			child !== null &&
			typeof child === 'object' &&
			!Array.isArray(child)
		) {
			const nestedResult = rewriteNestedRecord(
				child as Record<string, unknown>,
			);
			if (nestedResult.changed) changed = true;
			next[field] = nestedResult.next;
			continue;
		}
		next[field] = child;
	}

	// Surface SERVER_STRING_FIELDS that are absent — the engine wants
	// a consistent shape; we only rewrite what is there.
	for (const field of SERVER_STRING_FIELDS) {
		if (field in next) continue;
		if (field in entry) next[field] = entry[field];
	}

	return { changed, nextKey, nextValue: next };
};

const rewriteHostConfig = (
	config: Record<string, unknown>,
): { readonly changed: boolean; readonly next: Record<string, unknown> } => {
	const arrays = rewriteServerArrays(config);
	let changed = arrays.changed;
	const next: Record<string, unknown> = arrays.next;
	for (const mapName of SERVER_MAPS) {
		const map = next[mapName];
		if (map === null || typeof map !== 'object' || Array.isArray(map))
			continue;
		const rewritten: Record<string, unknown> = {};
		for (const [key, value] of Object.entries(
			map as Record<string, unknown>,
		)) {
			const result = rewriteServerEntry(key, value);
			if (result.changed) changed = true;
			rewritten[result.nextKey] = result.nextValue;
		}
		next[mapName] = rewritten;
	}
	return { changed, next };
};

/** A plain object — the shape whose members can be compared one by one. */
const isRecord = (value: unknown): value is Record<string, unknown> =>
	value !== null && typeof value === 'object' && !Array.isArray(value);

/**
 * The member-level differences between two values, as JSONC edits.
 *
 * A member that disappeared is a rename — the rewrite renames a server
 * by its own id — and a rename is applied by removing the old name and
 * adding the new one, which moves the server to the end of its map.
 * The caller replaces the whole map instead when that would happen, so
 * a renamed server keeps its place.
 */
const diffEdits = (
	before: unknown,
	after: unknown,
	path: readonly (string | number)[],
): readonly IJsoncEdit[] => {
	if (JSON.stringify(before) === JSON.stringify(after)) return [];
	if (!isRecord(before) || !isRecord(after)) return [{ path, value: after }];
	const edits: IJsoncEdit[] = [];
	for (const [key, child] of Object.entries(before)) {
		if (!Object.hasOwn(after, key)) {
			edits.push({ path: [...path, key], value: undefined });
			continue;
		}
		edits.push(...diffEdits(child, after[key], [...path, key]));
	}
	for (const [key, child] of Object.entries(after)) {
		if (!Object.hasOwn(before, key))
			edits.push({ path: [...path, key], value: child });
	}
	return edits;
};

/**
 * The edits that turn a parsed host config into its rewritten self.
 *
 * Every changed member is edited where it stands, so the comments
 * around it, the key order and the owner's own formatting all survive.
 */
const hostConfigEdits = (
	before: Record<string, unknown>,
	after: Record<string, unknown>,
): readonly IJsoncEdit[] => {
	const edits: IJsoncEdit[] = [];
	for (const [key, child] of Object.entries(after)) {
		const previous = before[key];
		if (previous === undefined) {
			edits.push({ path: [key], value: child });
			continue;
		}
		if (JSON.stringify(previous) === JSON.stringify(child)) continue;
		const nested = diffEdits(previous, child, [key]);
		// A member that disappeared was RENAMED. Removing it and adding
		// its new name would move the server to the end of its map, so
		// the map is replaced whole and keeps its order instead.
		if (nested.some((edit) => edit.value === undefined))
			edits.push({ path: [key], value: child });
		else edits.push(...nested);
	}
	return edits;
};

/**
 * The config's new text, or `undefined` when it names nothing to change.
 * The editor's and the root config are read leniently and rewritten in
 * place when they carry comments; the tolerant ones are read as JSONC
 * and skipped when even that fails.
 */
const rewrittenText = async (
	name: string,
	absolute: string,
): Promise<string | undefined> => {
	if (!TOLERANT_HOST_CONFIG_NAMES.has(name)) {
		const document = await readHostConfig(absolute);
		const { changed, next } = rewriteHostConfig(document.value);
		if (!changed) return undefined;
		// A plain JSON file is rewritten as it always was: the same
		// bytes, the same indentation, the same trailing newline. A file
		// that needed the lenient reader is edited in place instead, so
		// the comments it carries are still there afterwards.
		if (document.plain) return `${JSON.stringify(next, null, '\t')}\n`;
		const edits = hostConfigEdits(document.value, next);
		if (edits.length === 0) return undefined;
		return applyJsoncEdits(document.text, edits);
	}
	const raw = await readFile(absolute, 'utf8');
	const parsed = parseJsonc(raw);
	if (
		parsed.errors.length > 0 ||
		parsed.value === null ||
		typeof parsed.value !== 'object' ||
		Array.isArray(parsed.value)
	) {
		return undefined;
	}
	if (!rewriteHostConfig(parsed.value as Record<string, unknown>).changed) {
		return undefined;
	}
	return rewriteIdentityInString(raw);
};

/**
 * Factory: a fresh migrator instance. Pure at import time, side-effect
 * free until `apply` is called.
 */
export const createHostConfigMigrator = (): IMigration => {
	const present = async (ctx: IMigrationContext): Promise<string[]> => {
		const found: string[] = [];
		for (const name of HOST_CONFIG_NAMES) {
			if (await pathExists(join(ctx.workspaceRoot, name)))
				found.push(name);
		}
		return found;
	};
	const codexText = async (
		ctx: IMigrationContext,
	): Promise<string | undefined> => {
		const absolute = join(ctx.workspaceRoot, CODEX_CONFIG_NAME);
		return (await pathExists(absolute))
			? readFile(absolute, 'utf8')
			: undefined;
	};

	return {
		id: HOST_CONFIG_MIGRATOR_ID,

		detect: async (ctx) =>
			(await present(ctx)).length > 0 ||
			(await codexText(ctx)) !== undefined,

		plan: async (ctx): Promise<readonly IMigrationPlanStep[]> => {
			const steps: IMigrationPlanStep[] = [];
			for (const name of await present(ctx)) {
				const next = await rewrittenText(
					name,
					join(ctx.workspaceRoot, name),
				);
				if (next === undefined) continue;
				steps.push({
					kind: 'rewrite-host-config',
					detail: `${name}: legacy server / namespace / path rewritten`,
				});
			}
			const codex = await codexText(ctx);
			if (codex !== undefined && rewriteCodexConfig(codex) !== codex) {
				steps.push({
					kind: 'rewrite-host-config',
					detail: `${CODEX_CONFIG_NAME}: legacy server / namespace / path rewritten`,
				});
			}
			return steps;
		},

		apply: async (ctx) => {
			for (const name of await present(ctx)) {
				const absolute = join(ctx.workspaceRoot, name);
				const next = await rewrittenText(name, absolute);
				if (next !== undefined) await writeFileAtomic(absolute, next);
			}
			const codex = await codexText(ctx);
			if (codex !== undefined) {
				const rewritten = rewriteCodexConfig(codex);
				if (rewritten !== codex) {
					await writeFileAtomic(
						join(ctx.workspaceRoot, CODEX_CONFIG_NAME),
						rewritten,
					);
				}
			}
		},
	};
};

